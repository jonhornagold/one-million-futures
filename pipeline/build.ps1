<#
  One Million Futures: site build.

  Reads data/stories.json and writes data/stories.js, which contains only approved
  stories and is the file the web page loads. With -Out it also copies the publishable
  site into a folder (used by the GitHub Pages deploy).

  Usage:
    powershell -ExecutionPolicy Bypass -File pipeline\build.ps1
    powershell -ExecutionPolicy Bypass -File pipeline\build.ps1 -Out _site
#>
param([string]$Out)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$utf8 = New-Object System.Text.UTF8Encoding $false

$data = Get-Content (Join-Path $root "data\stories.json") -Raw -Encoding UTF8 | ConvertFrom-Json
$public = @($data.stories | Where-Object { $_.status -eq "approved" } | ForEach-Object {
  $o = [ordered]@{
    id = $_.id; type = $_.type; outlet = $_.outlet; title = $_.title; url = $_.url
    date = $_.date; summary = $_.summary; themes = @($_.themes)
  }
  if ($_.author)   { $o.author = $_.author }
  if ($_.featured) { $o.featured = $true }
  [pscustomobject]$o
})

$site = [ordered]@{
  lastUpdated = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
  review      = $data.review
  stories     = $public
}
$json = $site | ConvertTo-Json -Depth 8 -Compress
$js = "// Generated by pipeline/build.ps1. Do not edit; edit data/stories.json instead.`nwindow.OMF_DATA = " + $json + ";`n"
[IO.File]::WriteAllText((Join-Path $root "data\stories.js"), $js, $utf8)
Write-Host "Built data/stories.js with $($public.Count) approved stories (of $(@($data.stories).Count) total)."

if ($Out) {
  $dest = Join-Path $root $Out
  if (Test-Path $dest) { Remove-Item $dest -Recurse -Force }
  New-Item -ItemType Directory -Force (Join-Path $dest "data") | Out-Null
  Copy-Item (Join-Path $root "index.html") $dest
  Copy-Item (Join-Path $root "css") $dest -Recurse
  Copy-Item (Join-Path $root "js") $dest -Recurse
  Copy-Item (Join-Path $root "data\stories.js") (Join-Path $dest "data")
  New-Item -ItemType File (Join-Path $dest ".nojekyll") | Out-Null
  Write-Host "Copied site to $Out"
}
